// Compile the existing extraction instructions into Swift at build time.
// No JavaScript engine or source-code parser is required by the Mac app.
const fs = require('node:fs'), path = require('node:path'), ts = require('typescript');
const input = path.resolve(__dirname, '../../lib/enrichment/services/openai.ts');
const file = ts.createSourceFile(input, fs.readFileSync(input,'utf8'), ts.ScriptTarget.Latest, true);
const names = {extractStructuredDataOriginal:'original',extractStructuredDataWithCorroboration:'corroborated'};
const prompts = {};
function visit(node) {
  if (ts.isMethodDeclaration(node) && names[node.name.getText(file)]) {
    function search(n) {
      if (ts.isObjectLiteralExpression(n)) {
        const props = Object.fromEntries(n.properties.filter(ts.isPropertyAssignment).map(p=>[p.name.getText(file).replace(/['"]/g,''),p.initializer]));
        if(props.role && ts.isStringLiteralLike(props.role) && props.role.text==='system') {
          if(!props.content || !ts.isNoSubstitutionTemplateLiteral(props.content)) throw Error('Extraction system prompt is no longer static');
          const text = props.content.text;
          if(text.includes('"""#')) throw Error('Unsupported Swift raw delimiter');
          prompts[names[node.name.getText(file)]]=text;
        }
      }
      ts.forEachChild(n,search);
    }
    search(node);
  }
  ts.forEachChild(node,visit);
}
visit(file);
if(Object.keys(prompts).length!==2) throw Error('Missing original extraction prompts');
const result = '// Generated by generate-enrichment-prompts.cjs from the original OpenAI service.\n' +
  'enum NativeEnrichmentPrompts {\n' + Object.entries(prompts).map(([name,text])=>`    static let ${name} = #"""\n${text.split('\n').map(line=>'    '+line).join('\n')}\n    """#\n`).join('') + '}\n';
const destination = path.join(__dirname,'NativeEnrichmentPrompts.swift');
if(!fs.existsSync(destination) || fs.readFileSync(destination,'utf8')!==result) fs.writeFileSync(destination,result);
console.log('Compiled both original extraction prompts for native use');
