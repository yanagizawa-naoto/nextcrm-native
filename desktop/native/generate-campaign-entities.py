#!/usr/bin/env python3
"""Generate read-only HTML5 entity facts from Python's bundled standard table."""
from pathlib import Path
from html.entities import html5
rows = ['/* Generated by generate-campaign-entities.py from Python html.entities.html5. */',
        'static const struct { const char *name; const char *numeric; } entities[] = {']
for name, value in sorted(html5.items()):
    numeric = ''.join(f'&#x{ord(ch):x};' for ch in value)
    rows.append(f'    {{"{name}","{numeric}"}},')
rows.append('};')
Path(__file__).with_name('CampaignHTMLEntities.inc').write_text('\n'.join(rows)+'\n')
